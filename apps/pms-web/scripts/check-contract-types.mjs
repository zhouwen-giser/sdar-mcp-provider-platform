import { createHash } from "node:crypto";
import { readFile } from "node:fs/promises";
import { resolve } from "node:path";
import openapiTS, { astToString } from "openapi-typescript";

const root = resolve(process.cwd(), "../..");
const input = resolve(root, "contracts/pms-console-api/v1/openapi.yaml");
const lockPath = resolve(root, "contracts/pms-console-api/v1/contract-lock.json");
const generatedPath = resolve(process.cwd(), "src/api/generated/contract.d.ts");
const [openapi, lockRaw, checkedIn] = await Promise.all([
  readFile(input),
  readFile(lockPath, "utf8"),
  readFile(generatedPath, "utf8"),
]);
const lock = JSON.parse(lockRaw);
const canonicalOpenapi = Buffer.from(openapi.toString("utf8").replaceAll("\r\n", "\n"), "utf8");
const actualHash = createHash("sha256").update(canonicalOpenapi).digest("hex");
if (lock.status !== "frozen") throw new Error(`CONTRACT_NOT_FROZEN:${lock.status}`);
if (actualHash !== lock.openApiSha256) throw new Error(`CONTRACT_HASH_MISMATCH:${actualHash}`);
const ast = await openapiTS(new URL(`file://${input}`), { immutable: true });
const banner =
  "/* eslint-disable @typescript-eslint/consistent-indexed-object-style */\n/**\n * This file was auto-generated by openapi-typescript.\n * Do not make direct changes to the file.\n */\n\n";
const generated = `${banner}${astToString(ast)}`;
if (generated.replaceAll("\r\n", "\n") !== checkedIn.replaceAll("\r\n", "\n")) {
  throw new Error("GENERATED_CONTRACT_TYPES_OUT_OF_DATE");
}
console.log(`Contract check passed: ${lock.version} ${actualHash}`);
