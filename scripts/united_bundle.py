"""Checked, deterministic archives used by the five-component deployment bundle."""
import gzip
import hashlib
import io
from pathlib import Path, PurePosixPath
import re
import tarfile


def sha(data):
    return hashlib.sha256(data).hexdigest()


def safe_name(name):
    name = name.removeprefix('./').rstrip('/')
    path = PurePosixPath(name)
    if (not name or path.is_absolute() or '..' in path.parts or '\\' in name
            or any(c in name for c in '\r\n\0') or str(path) != name):
        raise ValueError('Unsafe archive path')
    return name


def read_archive(data, *, rooted=True, inventory=True):
    files, modes, seen, roots = {}, {}, set(), set()
    total = 0
    with tarfile.open(fileobj=io.BytesIO(data), mode='r:gz') as archive:
        for member in archive:
            name = safe_name(member.name)
            if name in seen or member.mode & 0o7000 or not (member.isfile() or member.isdir()):
                raise ValueError('Unsafe or duplicate archive member')
            seen.add(name)
            roots.add(name.split('/')[0])
            if member.isfile():
                total += member.size
                if total > 2 * 1024**3:
                    raise ValueError('Expanded archive exceeds 2 GiB')
                files[name] = archive.extractfile(member).read()
                modes[name] = member.mode & 0o777
    root = None
    if rooted:
        if len(roots) != 1:
            raise ValueError('Expected one archive root')
        root = roots.pop()
        if any(not name.startswith(root + '/') for name in files):
            raise ValueError('Archive root is not a directory')
        files = {name[len(root) + 1:]: data for name, data in files.items()}
        modes = {name[len(root) + 1:]: mode for name, mode in modes.items()}
    if any(str(parent) in files for name in files for parent in PurePosixPath(name).parents
           if str(parent) != '.'):
        raise ValueError('Archive file/directory conflict')
    if inventory:
        if 'SHA256SUMS' not in files:
            raise ValueError('Missing archive inventory')
        listed = {}
        for line in files['SHA256SUMS'].decode().splitlines():
            match = re.fullmatch(r'([a-f0-9]{64}) [ *](.+)', line)
            if not match:
                raise ValueError('Invalid inventory entry')
            name = safe_name(match[2])
            if name in listed:
                raise ValueError('Duplicate inventory entry')
            listed[name] = match[1]
        if set(listed) != set(files) - {'SHA256SUMS'}:
            raise ValueError('Incomplete archive inventory')
        if any(sha(files[name]) != digest for name, digest in listed.items()):
            raise ValueError('Archive inventory checksum mismatch')
    return root, files, modes


def checked_package(path, **options):
    path = Path(path)
    checksum = path.with_name(path.name + '.sha256')
    def signature(file):
        stat = file.stat()
        return stat.st_dev, stat.st_ino, stat.st_size, stat.st_mtime_ns, stat.st_ctime_ns
    before = signature(path), signature(checksum)
    data, line = path.read_bytes(), checksum.read_text().strip()
    if before != (signature(path), signature(checksum)) or line != sha(data) + '  ' + path.name:
        raise ValueError('Input changed or its checksum is invalid: ' + path.name)
    return data, read_archive(data, **options)


def write_archive(path, root, files, executable=()):
    path = Path(path)
    if '/' in safe_name(root):
        raise ValueError('Invalid root')
    files = dict(files)
    if 'SHA256SUMS' in files:
        raise ValueError('Inventory is generated by the archiver')
    for name in files:
        safe_name(name)
    files['SHA256SUMS'] = ''.join(f'{sha(data)}  {name}\n' for name, data in sorted(files.items())).encode()
    path.parent.mkdir(parents=True, exist_ok=True)
    temporary = path.with_name('.' + path.name + '.tmp')
    with temporary.open('wb') as raw, gzip.GzipFile(fileobj=raw, filename='', mode='wb', mtime=0) as gz, tarfile.open(fileobj=gz, mode='w') as archive:
        for name, data in sorted(files.items()):
            member = tarfile.TarInfo(root + '/' + name)
            member.size, member.mode = len(data), 0o755 if name in executable else 0o644
            archive.addfile(member, io.BytesIO(data))
    read_archive(temporary.read_bytes())
    temporary.replace(path)
    digest = sha(path.read_bytes())
    path.with_name(path.name + '.sha256').write_text(f'{digest}  {path.name}\n')
    return digest


def extract(data, destination):
    root, files, modes = read_archive(data)
    target = Path(destination) / root
    target.mkdir(parents=True, mode=0o755, exist_ok=False)
    for name, data in files.items():
        file = target / name
        file.parent.mkdir(parents=True, exist_ok=True)
        file.write_bytes(data)
        file.chmod(modes[name])
    return target
